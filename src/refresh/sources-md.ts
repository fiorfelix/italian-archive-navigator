import { writeFileSync } from 'node:fs';
import type { SourceRecord } from './build.js';
import { ISTAT_LICENCE } from './sources.js';

const ROUTE: Record<SourceRecord['route'], string> = {
  download: 'direct download of the published file',
  api: 'SITUAS public report service (documented at https://situas.istat.it/web/#/apiDetail)',
  manual: 'CSV exported by hand from the SITUAS website and placed in data/manual/',
};

/** Writes data/SOURCES.md from what this refresh actually used (SPEC §4, §8). */
export function writeSourcesMd(path: string, sources: SourceRecord[], refreshedAt: string): void {
  const out = [
    '# Data sources',
    '',
    `Generated by \`npm run refresh-data\` on ${refreshedAt}. Do not edit by hand.`,
    '',
    '## Attribution',
    '',
    'Contains data from ISTAT (Istituto Nazionale di Statistica), licensed under',
    `[${ISTAT_LICENCE.name}](https://creativecommons.org/licenses/by/4.0/deed.it).`,
    'Contains data from IndicePA (Indice dei domicili digitali della Pubblica Amministrazione',
    'e dei gestori di pubblici servizi, AgID), licensed under',
    '[Creative Commons Attribution 4.0](https://creativecommons.org/licenses/by/4.0/).',
    'Changes made: columns selected (names of office holders are not kept), names normalised',
    'for searching, and the tables joined into one SQLite database. Neither ISTAT nor AgID',
    'endorses this project.',
    '',
    `Licence statement on ${ISTAT_LICENCE.url}:`,
    '',
    `> ${ISTAT_LICENCE.text}`,
    '',
    '## Files used in this refresh',
    '',
  ];
  for (const s of sources) {
    out.push(
      `### ${s.title}`,
      '',
      `- Dataset page: ${s.page_url}`,
      `- Retrieved from: ${s.download_url}`,
      ...(s.metadata_url ? [`- Field definitions: ${s.metadata_url}`] : []),
      `- How: ${ROUTE[s.route]}`,
      `- File: \`${s.file_name}\` (${s.rows} data rows)`,
      `- SHA-256: \`${s.sha256}\``,
      `- Downloaded: ${s.downloaded_at}`,
      `- Licence: ${s.licence} — ${s.licence_url}`,
      '',
    );
  }
  out.push(
    '## Curated files (this project)',
    '',
    '- `data/curated/aliases.yaml` — frazioni and historical aliases. Every entry has its own',
    '  `source_url` and `verified` flag.',
    '- `data/curated/offices.yaml` — which Archivio di Stato serves each province, and pointers',
    '  to official directories for military and diocesan offices.',
    '',
  );
  writeFileSync(path, out.join('\n'));
}
